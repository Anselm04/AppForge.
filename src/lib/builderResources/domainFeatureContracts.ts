import { z } from "zod";
import type { BuildCapabilityId } from "../buildCapabilities.js";

const nonEmpty = z.string().trim().min(1);

export const domainFeatureContractSchema = z.object({
  featureId: nonEmpty,
  contractKind: z.enum([
    "data-model",
    "workflow",
    "integration",
    "ui",
    "platform",
    "security",
    "accessibility",
    "export",
    "research",
    "operations",
  ]),
  configurationKeys: z.array(nonEmpty).min(1),
  adaptationHooks: z.array(nonEmpty).min(1),
  testObligations: z.array(nonEmpty).min(1),
  securityObligations: z.array(nonEmpty).min(1),
});

export const domainFeaturePackSchema = z.object({
  capability: nonEmpty,
  features: z.array(domainFeatureContractSchema).min(1),
});

export type DomainFeatureContract = z.infer<typeof domainFeatureContractSchema>;
export type DomainFeaturePack = z.infer<typeof domainFeaturePackSchema>;

type FeatureKind = DomainFeatureContract["contractKind"];

function feature(
  featureId: string,
  contractKind: FeatureKind,
  options: {
    configurationKeys?: string[];
    adaptationHooks?: string[];
    testObligations?: string[];
    securityObligations?: string[];
  } = {},
): DomainFeatureContract {
  return domainFeatureContractSchema.parse({
    featureId,
    contractKind,
    configurationKeys: options.configurationKeys ?? [`${featureId}.configuration`],
    adaptationHooks: options.adaptationHooks ?? [`${featureId}.adapter`],
    testObligations: options.testObligations ?? [
      `validate ${featureId} contract behavior`,
    ],
    securityObligations: options.securityObligations ?? [
      "preserve ProductContract authorization and data boundaries",
    ],
  });
}

function pack(
  capability: BuildCapabilityId,
  features: DomainFeatureContract[],
): DomainFeaturePack {
  const parsed = domainFeaturePackSchema.parse({ capability, features });
  const ids = new Set<string>();
  for (const item of parsed.features) {
    if (ids.has(item.featureId)) {
      throw new Error(
        `Duplicate ${capability} Builder Resource feature: ${item.featureId}`,
      );
    }
    ids.add(item.featureId);
  }
  return parsed;
}

