export function validateDomainFeaturePack(
  capability: BuildCapabilityId,
  input: unknown,
): DomainFeaturePack {
  const parsed = domainFeaturePackSchema.parse(input);
  if (parsed.capability !== capability) {
    throw new Error(
      `Builder Resource feature pack capability mismatch: expected ${capability}, got ${parsed.capability}`,
    );
  }
  return parsed;
}

export function domainFeatureIds(
  capability: BuildCapabilityId,
): string[] {
  return DOMAIN_FEATURE_CONTRACTS[capability].features.map(
    (item) => item.featureId,
  );
}
