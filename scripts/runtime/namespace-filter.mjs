const ALLOW = 0x7fff0000;
const DENY = 0x00050001;
const UNSUPPORTED = 0x00050026;
const LD = 0x20,
  JEQ = 0x15,
  JSET = 0x45,
  RET = 0x06;

export function namespaceFilter() {
  if (process.arch !== "x64" || endianness() !== "LE")
    throw Error("Sandbox syscall policy is qualified only on Linux x86-64");
  const program = [
    [LD, 0, 0, 4],
    [JEQ, 1, 0, 0xc000003e],
    [RET, 0, 0, 0x80000000],
    [LD, 0, 0, 0],
    [JSET, 0, 1, 0x40000000],
    [RET, 0, 0, UNSUPPORTED],
    [JEQ, 0, 1, 435],
    [RET, 0, 0, UNSUPPORTED],
    [JEQ, 0, 4, 56],
    [LD, 0, 0, 16],
    [JSET, 0, 1, 0x7e020000],
    [RET, 0, 0, DENY],
    [RET, 0, 0, ALLOW],
    [JEQ, 0, 6, 16],
    [LD, 0, 0, 24],
    [JEQ, 0, 1, 0x5412],
    [RET, 0, 0, DENY],
    [JEQ, 0, 1, 0x541c],
    [RET, 0, 0, DENY],
    [RET, 0, 0, ALLOW],
  ];
  for (const number of ALLOWED)
    program.push([JEQ, 0, 1, number], [RET, 0, 0, ALLOW]);
  program.push([RET, 0, 0, DENY]);
  const buffer = Buffer.alloc(program.length * 8);
  program.forEach(([code, yes, no, value], index) => {
    const offset = index * 8;
    buffer.writeUInt16LE(code, offset);
    buffer.writeUInt8(yes, offset + 2);
    buffer.writeUInt8(no, offset + 3);
    buffer.writeUInt32LE(value, offset + 4);
  });
  return buffer;
}
if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  if (!process.argv[2]) throw Error("An output path is required");
  writeFileSync(process.argv[2], namespaceFilter(), { mode: 0o444 });
}
